"""Generates everything derived from spec/frame-v1.json.

    tools/generate.py                   validate the spec, regenerate outputs
    tools/generate.py --check           validate, and fail if any output is stale
    tools/generate.py --update-vectors  also (re)compute the hex in vectors/v1.json

Outputs:
    include/gnimu_frame/layout_v1.h   offsets, types, scales and mask bits for C++
    tests/vectors_v1.inc              the test vectors as C++ data
    docs/frame.md                     the field tables between <!-- generated:... --> markers

The vectors' hex is only computed with --update-vectors, never silently: once
committed, it's the fixed reference both encoders are tested against.
"""

import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gnimu_frame  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
LAYOUT_H = os.path.join(ROOT, "include", "gnimu_frame", "layout_v1.h")
VECTORS_JSON = os.path.join(ROOT, "vectors", "v1.json")
VECTORS_INC = os.path.join(ROOT, "tests", "vectors_v1.inc")
FRAME_MD = os.path.join(ROOT, "docs", "frame.md")

BANNER = "GENERATED by tools/generate.py from spec/frame-v1.json. Do not edit."
CPP_TYPES = {"u8": "U8", "i16": "I16", "u16": "U16", "i32": "I32", "f64": "F64"}
MASK_TYPES = ["mask8", "mask16", "mask32"]  # smallest first
MAX_FRAME_BYTES = 182  # one notification at the ATT MTU iOS negotiates (185)


def camel(key):
    return "".join(part.capitalize() for part in key.split("_"))


def size_of(spec, f):
    return f["bytes"] if f["type"] == "spare" else spec["types"][f["type"]]


def validate(spec):
    """Checks the layout and the block rules: each block is its valid mask,
    then its fields on bits 0, 1, 2 ..., then its spare bytes; the mask is the
    smallest type with at least one free bit per spare byte."""
    offset = 0
    for f in spec["header"]:
        assert f["offset"] == offset, "header %s at %d, expected %d" % (f["key"], f["offset"], offset)
        offset += size_of(spec, f)
    keys = set()
    total = 0
    for b in spec["blocks"]:
        name = b["key"]
        assert b["offset"] == offset, "block %s at %d, expected %d" % (name, b["offset"], offset)
        mask, *fields, spare = b["fields"]
        assert mask["type"] in MASK_TYPES, "block %s doesn't start with its valid mask" % name
        assert spare["type"] == "spare", "block %s doesn't end with spare bytes" % name
        for f in b["fields"]:
            assert f["key"] not in keys, "duplicate key " + f["key"]
            keys.add(f["key"])
            assert f["offset"] == offset, "%s at %d, expected %d" % (f["key"], f["offset"], offset)
            offset += size_of(spec, f)
        for bit, f in enumerate(fields):
            assert f.get("bit") == bit, "%s has bit %s, expected %d" % (f["key"], f.get("bit"), bit)
            # Optional: the OBD-II Service 01 PID for the same quantity, as
            # "0x0C", or "0x0B-0x33" for one PID minus another.
            if "obd2_pid" in f:
                assert re.fullmatch(r"0x[0-9A-F]{2}(-0x[0-9A-F]{2})?", f["obd2_pid"]), \
                    "%s has obd2_pid %r" % (f["key"], f["obd2_pid"])
            assert f["type"] in CPP_TYPES, "%s has type %s" % (f["key"], f["type"])
            assert f["scale"] in (None, 1, 10, 100, 1000), "%s has scale %s" % (f["key"], f["scale"])
        need = len(fields) + spare["bytes"]
        fits = [t for t in MASK_TYPES if spec["types"][t] * 8 >= need]
        assert fits, "block %s needs %d mask bits, more than a 32-bit mask holds" % (name, need)
        assert mask["type"] == fits[0], "block %s needs %d bits, so its mask should be %s, not %s" % (
            name, need, fits[0], mask["type"])
        assert offset - b["offset"] == b["bytes"], "block %s is %d bytes, says %d" % (name, offset - b["offset"], b["bytes"])
        total += len(fields)
    assert offset == spec["frame_bytes"], "frame is %d bytes, says %d" % (offset, spec["frame_bytes"])
    assert offset <= MAX_FRAME_BYTES, "frame is %d bytes, over the %d cap" % (offset, MAX_FRAME_BYTES)
    assert total == spec["field_count"], "%d fields, says %d" % (total, spec["field_count"])


def layout_header(spec):
    out = [
        "// " + BANNER,
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "namespace gnimu_frame {",
        "namespace v1 {",
        "",
        "constexpr uint8_t kSpecVersion = %d;" % spec["version"],
        "constexpr size_t kFrameBytes = %d;" % spec["frame_bytes"],
        "constexpr uint8_t kFieldCount = %d;" % spec["field_count"],
        "",
        "// Header",
    ]
    for f in spec["header"]:
        out.append("constexpr size_t k%sOffset = %d;" % (camel(f["key"]), f["offset"]))
    out += ["", "// Blocks: each starts with its valid mask"]
    for b in spec["blocks"]:
        m = b["fields"][0]
        out.append("constexpr size_t k%sMaskOffset = %d;  // %d bytes" % (
            camel(b["key"]), m["offset"], spec["types"][m["type"]]))
    out += ["", "enum class Type : uint8_t { U8, I16, U16, I32, F64 };", "",
            "// Index into kFields. The order carries no meaning on the wire.",
            "enum class Field : uint8_t {"]
    fields = gnimu_frame.data_fields(spec)
    for i, (b, f) in enumerate(fields):
        out.append("  %s = %d," % (camel(f["key"]), i))
    out += ["};", "",
            "// scale 0: no fixed scale (aux fields, defined by the device's schema).",
            "// A field's valid bit is bit `bit` of its block's mask, at `maskOffset`.",
            "struct FieldInfo {",
            "  uint8_t offset;",
            "  Type type;",
            "  uint16_t scale;",
            "  uint8_t maskOffset;",
            "  uint8_t bit;",
            "};", "",
            "constexpr FieldInfo kFields[kFieldCount] = {"]
    for b, f in fields:
        out.append("    {%d, Type::%s, %d, %d, %d},  // %s" % (
            f["offset"], CPP_TYPES[f["type"]], f["scale"] or 0, b["fields"][0]["offset"], f["bit"], f["key"]))
    out += ["};", "", "}  // namespace v1", "}  // namespace gnimu_frame", ""]
    return "\n".join(out)


def vectors_inc(vectors):
    out = ["// " + BANNER.replace("spec/frame-v1.json", "vectors/v1.json"),
           "// SPDX-License-Identifier: Apache-2.0", ""]
    for i, v in enumerate(vectors):
        out.append("static const VectorValue kVector%dValues[] = {" % i)
        for key, value in v["values"].items():
            out.append("    {Field::%s, %r}," % (camel(key), float(value)))
        out.append("};")
    out.append("static const Vector kVectors[] = {")
    for i, v in enumerate(vectors):
        h = v["header"]
        out.append('    {"%s", %d, %d, %d, %d, kVector%dValues, %d, "%s"},' % (
            v["name"], h["device_time_ms"], h["sequence"], h["capabilities"], h["state"], i, len(v["values"]), v["hex"]))
    out += ["};", ""]
    return "\n".join(out)


def md_pid(f):
    """A field's OBD-II PID cell: `0x0C`, or `0x0B` − `0x33`."""
    if "obd2_pid" not in f:
        return "—"
    return " − ".join("`%s`" % p for p in f["obd2_pid"].split("-"))


def md_table(spec, block):
    # A block with any OBD-II PIDs gets a column for them.
    pids = any("obd2_pid" in f for f in block["fields"])
    extra = (" Mode 01 PID |", "---|") if pids else ("", "")
    rows = ["| Bit | Offset | Type | Scale | Field | Unit |" + extra[0], "|---|---|---|---|---|---|" + extra[1]]
    for f in block["fields"]:
        cell = (" %s |" % md_pid(f)) if pids else ""
        if f["type"] in MASK_TYPES:
            rows.append("| — | %d | %s | — | **Valid mask** | bit *n* set: the field on bit *n* holds a real value |%s" % (
                f["offset"], "u%d" % (spec["types"][f["type"]] * 8), cell))
        elif f["type"] == "spare":
            rows.append("| — | %d | %d bytes | — | *Spare* | for fields added later |%s" % (f["offset"], f["bytes"], cell))
        else:
            scale = "*schema*" if f["scale"] is None else str(f["scale"])
            rows.append("| %d | %d | %s | %s | %s | %s |%s" % (
                f["bit"], f["offset"], f["type"], scale, f["name"], f["unit"], cell))
    return "\n".join(rows)


def md_header_table(spec):
    rows = ["| Offset | Type | Field | Meaning |", "|---|---|---|---|"]
    for f in spec["header"]:
        rows.append("| %d | %s | %s | %s |" % (f["offset"], f["type"], f["name"], f["unit"]))
    return "\n".join(rows)


def frame_md(spec, text):
    header_bytes = sum(size_of(spec, f) for f in spec["header"])
    sections = {"header": "*Offset 0, %d bytes.*\n\n%s" % (header_bytes, md_header_table(spec))}
    for b in spec["blocks"]:
        sections[b["key"]] = "*Offset %d, %d bytes.*\n\n%s" % (b["offset"], b["bytes"], md_table(spec, b))
    sections["summary"] = "**Total: %d bytes, %d fields.**" % (spec["frame_bytes"], spec["field_count"])

    def replace(m):
        key = m.group(1)
        if key not in sections:
            raise SystemExit("docs/frame.md has an unknown generated section '%s'" % key)
        return "<!-- generated:%s -->\n%s\n<!-- /generated -->" % (key, sections[key])

    return re.sub(r"<!-- generated:(\w+) -->.*?<!-- /generated -->", replace, text, flags=re.S)


def main(argv):
    check = "--check" in argv
    update_vectors = "--update-vectors" in argv
    spec = gnimu_frame.load_spec()
    validate(spec)

    with open(VECTORS_JSON, encoding="utf-8") as f:
        vectors = json.load(f)
    for v in vectors:
        hex_now = gnimu_frame.encode(v["header"], v["values"], spec).hex()
        if update_vectors:
            v["hex"] = hex_now
        elif not v.get("hex"):
            raise SystemExit("vector '%s' has no hex; run tools/generate.py --update-vectors" % v["name"])

    with open(FRAME_MD, encoding="utf-8") as f:
        md_now = f.read()
    outputs = {
        LAYOUT_H: layout_header(spec),
        VECTORS_INC: vectors_inc(vectors),
        FRAME_MD: frame_md(spec, md_now),
    }
    if update_vectors:
        outputs[VECTORS_JSON] = json.dumps(vectors, indent=2, ensure_ascii=False) + "\n"

    stale = []
    for path, content in outputs.items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == content:
            continue
        stale.append(os.path.relpath(path, ROOT))
        if not check:
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)

    if check and stale:
        print("Out of date: " + ", ".join(stale) + ". Run tools/generate.py and commit the result.", file=sys.stderr)
        return 1
    print("Updated: " + ", ".join(stale) if stale else "Everything is up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

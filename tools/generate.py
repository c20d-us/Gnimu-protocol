"""Generates everything derived from spec/frame-v1.json.

    tools/generate.py                   validate the spec, regenerate outputs
    tools/generate.py --check           validate, and fail if any output is stale
    tools/generate.py --update-vectors  also (re)compute the hex in vectors/v1.json

Outputs:
    include/gnimu_frame/layout_v1.h   offsets, types, scales and field numbers for C++
    tests/vectors_v1.inc              the test vectors as C++ data
    docs/frame.md                     the field tables between <!-- generated:... --> markers

The vectors' hex is only computed with --update-vectors, never silently: once
committed, it's the fixed reference both encoders are tested against.
"""

import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gnimu_frame  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
LAYOUT_H = os.path.join(ROOT, "include", "gnimu_frame", "layout_v1.h")
VECTORS_JSON = os.path.join(ROOT, "vectors", "v1.json")
VECTORS_INC = os.path.join(ROOT, "tests", "vectors_v1.inc")
FRAME_MD = os.path.join(ROOT, "docs", "frame.md")

BANNER = "GENERATED by tools/generate.py from spec/frame-v1.json. Do not edit."
CPP_TYPES = {"u8": "U8", "i16": "I16", "u16": "U16", "i32": "I32", "f64": "F64"}
MAX_FRAME_BYTES = 182  # one notification at the ATT MTU iOS negotiates (185)


def camel(key):
    return "".join(part.capitalize() for part in key.split("_"))


def validate(spec):
    sizes = spec["types"]
    offset = 0
    for f in spec["header"]:
        assert f["offset"] == offset, "header %s at %d, expected %d" % (f["key"], f["offset"], offset)
        offset += sizes[f["type"]]
    number = 0
    keys = set()
    for b in spec["blocks"]:
        assert b["offset"] == offset, "block %s at %d, expected %d" % (b["key"], b["offset"], offset)
        for f in b["fields"]:
            assert f["key"] not in keys, "duplicate key " + f["key"]
            keys.add(f["key"])
            assert f["offset"] == offset, "%s at %d, expected %d" % (f["key"], f["offset"], offset)
            offset += sizes[f["type"]]
            if not f.get("reserved"):
                assert f.get("number") == number, "%s numbered %s, expected %d" % (f["key"], f.get("number"), number)
                assert f["type"] in CPP_TYPES, "%s has non-field type %s" % (f["key"], f["type"])
                assert f["scale"] in (None, 1, 10, 100, 1000), "%s has scale %s" % (f["key"], f["scale"])
                number += 1
        assert offset - b["offset"] == b["bytes"], "block %s is %d bytes, says %d" % (b["key"], offset - b["offset"], b["bytes"])
    assert offset == spec["frame_bytes"], "frame is %d bytes, says %d" % (offset, spec["frame_bytes"])
    assert offset <= MAX_FRAME_BYTES, "frame is %d bytes, over the %d cap" % (offset, MAX_FRAME_BYTES)
    assert number == spec["field_count"], "%d fields, says %d" % (number, spec["field_count"])
    assert number <= 64, "%d fields don't fit a 64-bit mask" % number


def layout_header(spec):
    fields = gnimu_frame.numbered_fields(spec)
    out = [
        "// " + BANNER,
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "namespace gnimu_frame {",
        "namespace v1 {",
        "",
        "constexpr uint8_t kSpecVersion = %d;" % spec["version"],
        "constexpr size_t kFrameBytes = %d;" % spec["frame_bytes"],
        "constexpr uint8_t kFieldCount = %d;" % spec["field_count"],
        "",
        "// Header",
    ]
    for f in spec["header"]:
        out.append("constexpr size_t k%sOffset = %d;" % (camel(f["key"]), f["offset"]))
    out += ["", "enum class Type : uint8_t { U8, I16, U16, I32, F64 };", "",
            "// Field numbers: the index into kFields and the bit in the valid and fresh masks.",
            "enum class Field : uint8_t {"]
    for f in fields:
        out.append("  %s = %d," % (camel(f["key"]), f["number"]))
    out += ["};", "",
            "// scale 0: no fixed scale (aux fields, defined by the device's schema; spares).",
            "struct FieldInfo {",
            "  uint8_t offset;",
            "  Type type;",
            "  uint16_t scale;",
            "};", "",
            "constexpr FieldInfo kFields[kFieldCount] = {"]
    for f in fields:
        out.append("    {%d, Type::%s, %d},  // %d %s" % (f["offset"], CPP_TYPES[f["type"]], f["scale"] or 0,
                                                       f["number"], f["key"]))
    out += ["};", "", "}  // namespace v1", "}  // namespace gnimu_frame", ""]
    return "\n".join(out)


def vectors_inc(vectors):
    out = ["// " + BANNER.replace("spec/frame-v1.json", "vectors/v1.json"),
           "// SPDX-License-Identifier: Apache-2.0", ""]
    for i, v in enumerate(vectors):
        fresh = set(v.get("fresh", []))
        out.append("static const VectorValue kVector%dValues[] = {" % i)
        for key, value in v["values"].items():
            out.append("    {Field::%s, %r, %s}," % (camel(key), float(value), "true" if key in fresh else "false"))
        out.append("};")
    out.append("static const Vector kVectors[] = {")
    for i, v in enumerate(vectors):
        h = v["header"]
        out.append('    {"%s", %d, %d, %d, %d, kVector%dValues, %d, "%s"},' % (
            v["name"], h["device_time_ms"], h["sequence"], h["device_type"], h["state"], i, len(v["values"]), v["hex"]))
    out += ["};", ""]
    return "\n".join(out)


def md_table(spec, block):
    rows = ["| # | Offset | Type | Scale | Field | Unit |", "|---|---|---|---|---|---|"]
    for f in block["fields"]:
        if f.get("reserved"):
            rows.append("| — | %d | %s | — | *Reserved* | %s |" % (f["offset"], f["type"], f["unit"]))
        elif f.get("spare"):
            rows.append("| %d | %d | %s | — | *Spare* | |" % (f["number"], f["offset"], f["type"]))
        else:
            scale = "*schema*" if f["scale"] is None else str(f["scale"])
            rows.append("| %d | %d | %s | %s | %s | %s |" % (f["number"], f["offset"], f["type"], scale, f["name"], f["unit"]))
    return "\n".join(rows)


def md_header_table(spec):
    rows = ["| Offset | Type | Scale | Field | Unit / meaning |", "|---|---|---|---|---|"]
    for f in spec["header"]:
        t = "8 bytes" if f["type"] == "mask64" else f["type"]
        scale = "—" if f["scale"] is None else str(f["scale"])
        rows.append("| %d | %s | %s | %s | %s |" % (f["offset"], t, scale, f["name"], f["unit"]))
    return "\n".join(rows)


def frame_md(spec, text):
    sections = {"header": md_header_table(spec)}
    for b in spec["blocks"]:
        sections[b["key"]] = md_table(spec, b)
    sections["summary"] = "**Total: %d bytes, %d fields.** Mask bits %d–63 are unused." % (
        spec["frame_bytes"], spec["field_count"], spec["field_count"])

    def replace(m):
        key = m.group(1)
        if key not in sections:
            raise SystemExit("docs/frame.md has an unknown generated section '%s'" % key)
        return "<!-- generated:%s -->\n%s\n<!-- /generated -->" % (key, sections[key])

    return re.sub(r"<!-- generated:(\w+) -->.*?<!-- /generated -->", replace, text, flags=re.S)


def main(argv):
    check = "--check" in argv
    update_vectors = "--update-vectors" in argv
    spec = gnimu_frame.load_spec()
    validate(spec)

    with open(VECTORS_JSON, encoding="utf-8") as f:
        vectors = json.load(f)
    for v in vectors:
        hex_now = gnimu_frame.encode(v["header"], v["values"], v.get("fresh", []), spec).hex()
        if update_vectors:
            v["hex"] = hex_now
        elif not v.get("hex"):
            raise SystemExit("vector '%s' has no hex; run tools/generate.py --update-vectors" % v["name"])

    with open(FRAME_MD, encoding="utf-8") as f:
        md_now = f.read()
    outputs = {
        LAYOUT_H: layout_header(spec),
        VECTORS_INC: vectors_inc(vectors),
        FRAME_MD: frame_md(spec, md_now),
    }
    if update_vectors:
        outputs[VECTORS_JSON] = json.dumps(vectors, indent=2, ensure_ascii=False) + "\n"

    stale = []
    for path, content in outputs.items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == content:
            continue
        stale.append(os.path.relpath(path, ROOT))
        if not check:
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)

    if check and stale:
        print("Out of date: " + ", ".join(stale) + ". Run tools/generate.py and commit the result.", file=sys.stderr)
        return 1
    print("Updated: " + ", ".join(stale) if stale else "Everything is up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
